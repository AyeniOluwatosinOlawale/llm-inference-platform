#!/usr/bin/env bash
# Generate cryptographically random secrets for all platform components.
# Output is written to .env.secrets (gitignored).
# Run once before the first deploy: make secrets
set -euo pipefail

OUT=".env.secrets"

if [ -f "$OUT" ]; then
  echo "Warning: $OUT already exists. Delete it to regenerate."
  exit 1
fi

echo "==> Generating secrets..."

LITELLM_MASTER_KEY="sk-$(openssl rand -hex 24)"
REDIS_PASSWORD="$(openssl rand -base64 32 | tr -dc 'a-zA-Z0-9' | head -c 32)"
POSTGRES_PASSWORD="$(openssl rand -base64 32 | tr -dc 'a-zA-Z0-9' | head -c 32)"
GRAFANA_PASSWORD="$(openssl rand -base64 24 | tr -dc 'a-zA-Z0-9' | head -c 24)"

cat > "$OUT" <<EOF
# Generated by scripts/generate-secrets.sh — DO NOT COMMIT
LITELLM_MASTER_KEY=${LITELLM_MASTER_KEY}
REDIS_PASSWORD=${REDIS_PASSWORD}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
GRAFANA_ADMIN_PASSWORD=${GRAFANA_PASSWORD}
DATABASE_URL=postgresql://litellm:${POSTGRES_PASSWORD}@postgres-service.llm-gateway.svc.cluster.local:5432/litellm
HUGGINGFACE_TOKEN=REPLACE_ME

# Slack alerts — AlertManager posts to #all-llm-platform-alerts
# Paste your webhook URL here (from api.slack.com/apps → Incoming Webhooks)
SLACK_WEBHOOK_URL=REPLACE_ME

# Velero cluster backup
VELERO_BACKUP_BUCKET=llm-inference-platform-velero-backups
AWS_REGION=us-east-1
VELERO_AWS_ACCESS_KEY_ID=REPLACE_ME
VELERO_AWS_SECRET_ACCESS_KEY=REPLACE_ME
EOF

chmod 600 "$OUT"
echo "==> Secrets written to $OUT"
echo "    LITELLM_MASTER_KEY=${LITELLM_MASTER_KEY:0:12}..."
echo "    REDIS_PASSWORD=****"
echo "    POSTGRES_PASSWORD=****"
echo "    GRAFANA_ADMIN_PASSWORD=****"
